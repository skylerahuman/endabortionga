import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { REGIONS } from '../src/lib/config/regions.ts';

const input = resolve(process.argv[2] ?? '../ga-gms-map/data/districts.json');
const data = JSON.parse(await readFile(input, 'utf8'));
const metrics = REGIONS.map((region) => {
	const features = region.districts.map((id) => data.features.find((feature) => feature.id === id));
	if (features.some((feature) => !feature)) throw new Error(`Unknown district in ${region.id}`);
	const population = features.reduce(
		(sum, feature) => sum + Number(feature.properties.financial?.population ?? 0),
		0
	);
	const households = features.reduce(
		(sum, feature) => sum + Number(feature.properties.financial?.households ?? 0),
		0
	);
	const weightedIncome = features.reduce(
		(sum, feature) =>
			sum +
			Number(feature.properties.financial?.medianHouseholdIncome ?? 0) *
				Number(feature.properties.financial?.households ?? 0),
		0
	);
	return {
		id: region.id,
		name: region.name,
		population,
		households,
		medianHouseholdIncome: Math.round(weightedIncome / households)
	};
});
const statewidePopulation = metrics.reduce((sum, metric) => sum + metric.population, 0);
const statewideHouseholds = metrics.reduce((sum, metric) => sum + metric.households, 0);
const statewideWeightedIncome = metrics.reduce(
	(sum, metric) => sum + metric.medianHouseholdIncome * metric.households,
	0
);
const statewideMedianIncome = Math.round(statewideWeightedIncome / statewideHouseholds);
const source = `ACS 2023 5-year B19013; populations estimated from county intersections by ga-gms-map ${data.metadata?.generatedAt ?? ''}`;
const output = `// Generated by scripts/build-region-metrics.mjs. Do not edit by hand.\nexport const REGION_METRICS_SOURCE = ${JSON.stringify(source)};\nexport const STATEWIDE_POPULATION = ${statewidePopulation};\nexport const STATEWIDE_MEDIAN_INCOME = ${statewideMedianIncome};\nexport const REGION_METRICS = ${JSON.stringify(Object.fromEntries(metrics.map((metric) => [metric.id, metric])), null, '\t')} as const;\n`;
await writeFile(new URL('../src/lib/config/region-metrics.ts', import.meta.url), output);
console.log(
	`Built metrics for ${metrics.length} regions; statewide population ${statewidePopulation}.`
);
